//! Generates the TypeScript and Swift protocol types from the Rust ones.
//!
//! Rust is the single source: `schemars` derives a JSON Schema from the serde types (it honours
//! `tag`, `flatten`, `untagged`, `rename`, `skip_serializing_if`...), and the two small emitters
//! below turn that schema into TypeScript and Swift. Run `cargo run -p openpedal-protocol --bin
//! gen-protocol`; CI fails when the checked-in output is stale.

mod model;
mod swift;
mod typescript;

use schemars::generate::SchemaSettings;

use crate::{ClientMsg, ServerMsg, PROTOCOL_VERSION};
use openpedal_graph::model as graph;

pub(crate) const HEADER: &str = "// @generated by `cargo run -p openpedal-protocol --bin gen-protocol`. DO NOT EDIT.\n// Source of truth: the Rust types in crates/protocol, crates/graph and crates/dsp.";

/// JSON Schema (draft 2020-12, serialize side: the shape the Rust types emit) of every type
/// reachable from `ClientMsg` and `ServerMsg`, as a `{name: schema}` map.
pub fn schema() -> serde_json::Map<String, serde_json::Value> {
    let mut g = SchemaSettings::draft2020_12().for_serialize().into_generator();
    g.subschema_for::<ClientMsg>();
    g.subschema_for::<ServerMsg>();
    g.take_definitions(true)
}

fn consts() -> Vec<(&'static str, String)> {
    vec![
        ("PROTOCOL_VERSION", PROTOCOL_VERSION.to_string()),
        ("INPUT", format!("{:?}", graph::INPUT)),
        ("OUTPUT", format!("{:?}", graph::OUTPUT)),
        ("PEDAL_PREFIX", format!("{:?}", graph::PEDAL_PREFIX)),
        ("PEDAL_IN", format!("{:?}", graph::PEDAL_IN)),
        ("PEDAL_OUT", format!("{:?}", graph::PEDAL_OUT)),
    ]
}

pub fn typescript() -> String {
    typescript::generate(&model::parse(&schema()), &consts())
}

pub fn swift() -> String {
    swift::generate(&model::parse(&schema()), &consts())
}

/// Doc comment lines of a schema description.
pub(crate) fn doc_lines(d: &Option<String>) -> Vec<String> {
    d.as_deref().map(|s| s.lines().map(|l| l.trim_end().to_owned()).collect()).unwrap_or_default()
}
